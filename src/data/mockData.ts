const generateUsageHistory = (days: number, baseUsage: number, variance: number): { date: string; usage: number }[] => {
  const history: { date: string; usage: number }[] = [];
  const today = new Date();
  for (let i = days - 1; i >= 0; i--) {
    const date = new Date(today);
    date.setDate(date.getDate() - i);
    const usage = Math.round(baseUsage + (Math.random() - 0.5) * variance);
    history.push({
      date: date.toISOString().split('T')[0],
      usage: Math.max(0, usage),
    });
  }
  return history;
};

